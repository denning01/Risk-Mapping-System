    ENV_DRIFT=$(( ENV_DRIFT + 1 ))
    printf '| `%s` | %s | **%s** |\n' "$k" "$agree" "$(echo "$bad" | sed 's/^ //')"
  else
    printf '| `%s` | %s | — |\n' "$k" "$agree"
  fi
done

MERGE_DEBT=0
echo ""
echo "### Merge debt — an accepted round that has not reached \`main\`"
echo ""
echo "The rule (AGENTS.md, 2026-09-27): once a round is ACCEPTED and its findings are closed, it is"
echo "merged to \`main\` **before the next unit of work starts**, so every task begins from a clean"
echo "tree at data's tip. A row below that says DEBT is a branch that owes that merge."
echo ""
echo "| Role | Last round | Verdict | Audited commit | In \`main\`? | Commits past it | State |"
echo "|---|---|---|---|---|---|---|"
for role in $ROLES; do
  f="$AUDIT_DIR/$role.md"; d="$DEV_ROOT/$(wt_dir "$role")"; b="$(wt_brch "$role")"
  IFS='|' read -r lr _ <<<"$(last_round "$f" LEAD)"
  if [ -z "$lr" ]; then
    printf '| %s | — | — | — | — | — | no rounds yet |\n' "$role"; continue
  fi
  v="$(round_verdict "$f" "$lr")"; sha="$(round_commit "$f" "$lr")"
  inmain="—"; past="—"; state=""
  if [ -n "$sha" ] && [ -d "$d" ]; then
    if git -C "$d" cat-file -e "${sha}^{commit}" 2>/dev/null; then
      if git -C "$d" merge-base --is-ancestor "$sha" data 2>/dev/null; then inmain="yes"; else inmain="**no**"; fi
      past="$(git -C "$d" rev-list --count "$sha..$b" 2>/dev/null || echo '?')"
    else
      inmain="commit missing"
    fi
  fi
  case "$v" in
    ACCEPT)
      if [ "$inmain" = "yes" ]; then state="clear"
      else state="**DEBT — merge before the next round**"; MERGE_DEBT=$(( MERGE_DEBT + 1 )); fi ;;
    REJECT) state="rejected — lead owes a fix" ;;
    "")     state="awaiting verdict" ;;
    *)      state="$v" ;;
  esac
  printf '| %s | %s | %s | `%s` | %s | %s | %s |\n' "$role" "$lr" "${v:-—}" "${sha:-none named}" "$inmain" "$past" "$state"
done
