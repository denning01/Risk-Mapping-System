    fi
  fi
  owedtxt=$([ "$owed" = 0 ] && echo "—" || echo "**$owed round(s) unaudited**")
  printf '| %s | %s | %s | %s | %s | %s | %s |\n' "$role" "${lr:-—}" "${dl:-—}" "${ar:-—}" "${dr:-—}" "$v" "$owedtxt"
done

echo ""
if [ -n "$(ls "$WATCH_DIR"/*.held 2>/dev/null)" ]; then
  echo "**Watcher holds — a delivery it refused to make, and why:**"
  echo ""
  echo '```'
  for h in "$WATCH_DIR"/*.held; do
    printf '%-14s %s   (recorded %s)\n' "$(basename "$h" .held):" "$(cat "$h")" "$(ago "$(mtime "$h")")"
  done
  echo '```'
else
  echo "Watcher holds: none."
fi

MAIL_OPEN=0; MAIL_LATE=0; MAIL_LATE_LIST=""
echo ""
echo "### Message rail — lead to operator, operator to lead"
echo ""
echo "Open traffic on \`rms-audit/mail\`. A \`blocking\` message is one whose sender is stopped"
echo "until it is answered; one older than ${MAIL_STALE_H}h fails the self-check below, because a"
echo "question nobody answers is how this grid stalls. There is no lead-to-lead edge by design, and"
echo "the rail cannot carry a ruling or a go-ahead — \`scripts/agent-msg.sh\` refuses both."
echo ""
if [ -n "$(ls "$MAIL_DIR"/pending/*.md "$MAIL_DIR"/delivered/*.md 2>/dev/null)" ]; then
  echo "| Age | From | To | Kind | State | Blocking | Subject |"
  echo "|---|---|---|---|---|---|---|"
  for d in pending delivered; do
    for f in "$MAIL_DIR/$d"/*.md; do
      [ -f "$f" ] || continue
      MAIL_OPEN=$(( MAIL_OPEN + 1 ))
      m="$(mtime "$f")"; age="$(ago "$m")"; blk="$(mail_hdr "$f" blocking)"
      if [ "$blk" = yes ] && [ -n "$m" ] && [ $(( (now_s - m) / 3600 )) -ge "$MAIL_STALE_H" ]; then
        MAIL_LATE=$(( MAIL_LATE + 1 ))
        MAIL_LATE_LIST="$MAIL_LATE_LIST $(mail_hdr "$f" id)"
        blk="**YES, $(( (now_s - m) / 3600 ))h**"
      fi
      printf '| %s | %s | %s | %s | %s | %s | %s |\n' "$age" "$(mail_hdr "$f" from)" \
        "$(mail_hdr "$f" to)" "$(mail_hdr "$f" kind)" "$d" "${blk:-no}" \
        "$(mail_hdr "$f" subject | cut -c1-70)"
    done
  done
  echo ""
  echo "Resolved threads are kept in \`mail/resolved/\` and are not listed. \`npm run msg -- list\`"
  echo "shows everything; \`npm run msg -- read <id>\` shows one."
else
  echo "No open messages."
fi

ENV_DRIFT=0
echo ""
echo "### Config drift across worktrees"
echo ""
echo "Values that must be identical in every worktree's \`.env\`. Compared, never printed — the other"
echo "lines in those files are credentials. A worktree is listed if it disagrees or does not set it."
echo ""
echo "| Value | Worktrees agreeing | Disagreeing |"
echo "|---|---|---|"
for k in $ENV_KEYS_WATCHED; do
  ref=""; agree=0; bad=""
  for d in "$DEV_ROOT"/rms "$DEV_ROOT"/rms-*; do
    [ -f "$d/.env" ] || continue
    v="$(env_value "$d/.env" "$k")"
    [ -z "$ref" ] && ref="$v"
    if [ -n "$v" ] && [ "$v" = "$ref" ]; then agree=$(( agree + 1 ))
    else bad="$bad \`$(basename "$d")\`"; fi
  done
