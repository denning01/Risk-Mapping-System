## 1. Grid

tmux session \`$SESSION\`: $([ "$have_tmux" = 1 ] && echo "present" || echo "**ABSENT — run npm run agents:boot**")
Watcher: **$W_STATE** — process $W_PROC, last loop $W_BEAT (heartbeat is the liveness signal; a pid
only proves a process exists).

| Role | Window | Panes (real process) | Session | Worktree | Branch |
|---|---|---|---|---|---|
HDR

for role in operator $ROLES; do
  cmds="$(pane_cmds "$role")"; st="$(live_state "$cmds")"
  d="$(wt_dir "$role")"; b="$(wt_brch "$role")"
  printf '| %s | %s | `%s` | **%s** | `../%s` | `%s` |\n' "$role" "$role" "$cmds" "$st" "$d" "$b"
done

cat <<'MID'

`STARTED` means a non-shell process is in the pane. `queued (idle)` means the window and worktree
exist but no agent is running in them — the layout being right says nothing about anything running,
which is CLAUDE.md rule 11.

---

## 2. Round ledger — what the watcher queued vs what the agents actually worked

The tally the grid can get wrong. Columns, left to right: what the **lead wrote**, what the
**watcher handed to the auditor**, what the **auditor answered**, what the watcher handed back.
A gap between columns 1 and 3 is unaudited work sitting still.

| Role | Lead wrote | → delivered to auditor | Auditor answered | → returned to lead | Last verdict | Owed |
|---|---|---|---|---|---|---|
MID

OWED_TOTAL=0; STALLED=""; STALL_N=0
for role in $ROLES; do
  f="$AUDIT_DIR/$role.md"
  IFS='|' read -r lr _ <<<"$(last_round "$f" LEAD)"
  IFS='|' read -r ar _ <<<"$(last_round "$f" AUDITOR)"
  dl="$(marker_round "$WATCH_DIR/$role.delivered")"
  dr="$(marker_round "$WATCH_DIR/$role.lead-delivered")"
  v="$(last_verdict "$f")"
  owed=0
  if [ -n "$lr" ] && [ -n "$ar" ]; then owed=$(( lr - ar )); [ "$owed" -lt 0 ] && owed=0
  elif [ -n "$lr" ] && [ -z "$ar" ]; then owed="$lr"; fi
  [ "$owed" != 0 ] && OWED_TOTAL=$(( OWED_TOTAL + owed ))
  if [ "$owed" != 0 ]; then
    agev="$(delivered_age_h "$role")"
    if [ -n "$agev" ] && [ "$agev" -ge "$STALL_HOURS" ]; then
