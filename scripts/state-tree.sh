**Generated $(date '+%Y-%m-%d %H:%M:%S %Z') by \`scripts/state-tree.sh\`. Do not hand-edit — the next
run overwrites it.** Regenerate with \`npm run state\`. The watcher also regenerates it about once a
minute, so this file keeps updating with no Claude session alive.

Every figure below is derived at generation time from tmux, git, the exchange logs and the watcher's
own markers. Nothing here is remembered from a transcript. If a line contradicts \`git\` or
\`npm run agents\`, those win and this file is stale — say so rather than working around it.

---

## 0. Cold start — the machine just came back on

\`\`\`
cd /Users/mac/IGAD/rms
npm run agents:boot                  # rebuild the tmux grid, restart what WAS live
npm run agents                       # what is queued vs started, and the watcher's health
npm run state -- --show              # this file, regenerated
cat /Users/mac/IGAD/rms-audit/STATE.md
\`\`\`

Nothing below needs a transcript to interpret. A different model, a different provider or a human
