#!/usr/bin/env bash
# Writes rms-audit/STATE.md — the one file that says what is happening right now.
#
#   npm run state            regenerate and print the path
#   npm run state -- --show  regenerate and cat it
#   npm run state -- --check exit 1 if the picture is internally inconsistent
#
# WHY THIS IS GENERATED AND NOT WRITTEN BY HAND
# A hand-maintained status file is the exact failure CLAUDE.md rule 11 names: the RLS model list was
# hand-kept, drifted, and was blind to 10 of 40 models while printing a green tick. So every number
# here is derived, at read time, from something that cannot be politely wrong:
#
#   grid liveness      tmux pane_current_command   (not the pane title, which Claude overwrites)
#   branch position    git rev-list --count        (not a remembered "ahead by ~20")
#   round ledger       the exchange logs + the watcher's own delivery markers, compared
#   task tree          rms-audit/tasks/<role>.md, the files the leads actually edit
#   findings           the exchange logs, anchored parse
#   watcher health     heartbeat mtime             (a pid proves a process, not a loop)
#
# It is regenerated by the watcher every MEM_INTERVAL seconds, so it stays current with no session
# alive at all — which is the point: it has to survive the machine going off mid-task.
set -uo pipefail

DEV_ROOT="${AGENTS_DEV_ROOT:-$(cd "$(dirname "$0")/../.." && pwd)}"
AUDIT_DIR="$DEV_ROOT/rms-audit"
WATCH_DIR="$AUDIT_DIR/.watch"
STATE_DIR="$AUDIT_DIR/.state"
TASK_DIR="$AUDIT_DIR/tasks"
OUT="$AUDIT_DIR/STATE.md"
SESSION="${AGENTS_SESSION:-igad}"
ROLES="model exposure"
SHOW=0; CHECK=0
for a in "$@"; do case "$a" in --show) SHOW=1 ;; --check) CHECK=1 ;; esac; done
mkdir -p "$AUDIT_DIR"

# role -> worktree dir | branch
wt_dir()  { case "$1" in operator) echo rms ;; model) echo rms-model ;; exposure) echo rms-exposure ;; esac; }
wt_brch() { case "$1" in operator) echo data ;; model) echo a/model ;; exposure) echo a/exposure ;; esac; }

now_s=$(date +%s)
ago() { # seconds -> human
  local s="${1:-}"; [ -z "$s" ] && { echo "never"; return; }
  local d=$(( now_s - s ))
  if   [ "$d" -lt 0 ]    ; then echo "in the future (clock skew)"
  elif [ "$d" -lt 90 ]   ; then echo "${d}s ago"
  elif [ "$d" -lt 5400 ] ; then echo "$(( d / 60 ))m ago"
  elif [ "$d" -lt 172800 ]; then echo "$(( d / 3600 ))h ago"
  else echo "$(( d / 86400 ))d ago"; fi
}
mtime() { [ -f "$1" ] && stat -f %m "$1" 2>/dev/null || echo ""; }

INCONSISTENT=0
note_bad() { INCONSISTENT=1; }

# ---------------------------------------------------------------- watcher health
W_PID="$(cat "$WATCH_DIR/pid" 2>/dev/null || true)"
W_HB="$(cat "$WATCH_DIR/heartbeat" 2>/dev/null || true)"
if [ -n "$W_PID" ] && kill -0 "$W_PID" 2>/dev/null; then W_PROC="alive (pid $W_PID)"; else W_PROC="DEAD"; fi
if [ -n "$W_HB" ]; then W_BEAT="$(ago "$W_HB")"; W_LAG=$(( now_s - W_HB )); else W_BEAT="never"; W_LAG=999999; fi
if [ "$W_PROC" = "DEAD" ] || [ "$W_LAG" -gt 60 ]; then W_STATE="STUCK OR DOWN"; note_bad; else W_STATE="running"; fi

# ---------------------------------------------------------------- grid liveness
have_tmux=0
tmux has-session -t "$SESSION" 2>/dev/null && have_tmux=1

pane_cmds() { # role -> "cmd cmd" for its window's panes, in order
  [ "$have_tmux" = 1 ] || { echo "-"; return; }
  tmux list-panes -t "$SESSION:$1" -F '#{pane_current_command}' 2>/dev/null | tr '\n' ' ' | sed 's/ $//'
  [ -z "$(tmux list-panes -t "$SESSION:$1" -F x 2>/dev/null)" ] && echo -n "-"
}
live_state() { # a pane running anything that is not a plain shell is a started session
  local cmds="$1" c
  [ "$cmds" = "-" ] && { echo "not built"; return; }
  for c in $cmds; do
    case "$c" in zsh|bash|sh|fish|login) ;; *) echo STARTED; return ;; esac
  done
  echo "queued (idle)"
}

# ---------------------------------------------------------------- round ledger
last_round() { # file, LEAD|AUDITOR -> "N|line"
  local f="$1" who="$2"
  [ -f "$f" ] || { echo "|"; return; }
  local l; l="$(grep -E "^ROUND [0-9]+ · $who ·" "$f" 2>/dev/null | tail -1)"
  [ -z "$l" ] && { echo "|"; return; }
  echo "$(echo "$l" | awk '{print $2}')|$l"
}
last_verdict() {
  local f="$1"; [ -f "$f" ] || { echo "—"; return; }
  local v; v="$(grep -oE 'VERDICT: *(ACCEPT|REJECT)' "$f" 2>/dev/null | tail -1 | awk '{print $2}')"
  echo "${v:-—}"
}
marker_round() { # .delivered / .lead-delivered -> N
  local f="$1"; [ -f "$f" ] || { echo "—"; return; }
  awk '{print $2}' "$f" 2>/dev/null | head -1
}

# ---------------------------------------------------------------- message rail
# rms-audit/mail/ is the lead<->operator rail (scripts/agent-msg.sh). It is surfaced here for one
# reason: a question nobody answers is how this grid stalls. Four leads sat blocked 3-5 hours on
# 2026-09-22 waiting to be noticed, and a payments question took three operator round-trips over
# five days. So an unanswered BLOCKING message is a failing check, not a thing someone remembers.
MAIL_DIR="$AUDIT_DIR/mail"
MAIL_STALE_H="${MAIL_STALE_H:-2}"
mail_hdr() { sed -n "s/^$2:[[:space:]]*//p" "$1" 2>/dev/null | head -1; }

# ---------------------------------------------------------------- stall age
# A round owed for ten minutes is work in progress. A round owed for eight hours is a stall nobody
# noticed. Until 2026-09-27 the grid had no signal for the difference: STATE.md said "N round(s)
# owed" whether the auditor was mid-command or had been blocked on a permission dialog since
# breakfast. Three separate multi-hour stalls were found only because somebody went and looked --
# twice by the operator, once after two full days.
#
# So the AGE is measured, not just the count. The clock starts when the watcher delivered the round,
# which is a timestamp the watcher owns and the auditor cannot influence.
# A STALL FIGURE IS A READING, NOT A STATE, AND IT EXPIRES. Raised by feat/dashboard-ui on
# 2026-09-28 after the operator asked it whether it was blocked, citing a 12h stall: the reading was
# correct when taken and stopped being true about SIXTY SECONDS later, when its auditor returned a
# verdict. "12h stalled, measured 1s ago" and "12h stalled, measured 20 minutes ago" looked
# identical in this file and are completely different facts. So the reading's own timestamp is
# printed beside it. This is the AGENTS.md norm about stale instructions applied to this file's own
# output — a number here is a claim about the world at generation time.
STALL_HOURS="${STALL_HOURS:-2}"
delivered_age_h() {  # $1=role -> whole hours since the watcher handed the current round over
  local f="$WATCH_DIR/$1.delivered" m
  m="$(mtime "$f")"; [ -n "$m" ] || { echo ""; return; }
  echo $(( (now_s - m) / 3600 ))
}

# ---------------------------------------------------------------- env drift
# One value, eleven files, kept in sync by discipline — the exact shape this repo keeps getting
# caught by (the settings-file credentials; the DIRECT_URL rotation five audit worktrees missed;
# and on 2026-09-27 AWS_KMS_KEY_ID, where ten worktrees sat on one dead LocalStack key and
# feat/payments on a second, different dead key. Nothing said so — gate 5 just stayed red on every
# branch and was blamed on Docker for days.)
#
# Addressing the key by a stable alias means the value should now never change, which makes drift
# both unlikely AND silent — the worst combination. So it is checked every minute rather than
# trusted, and a worktree created tomorrow that misses it shows up as a row instead of a mystery.
# Values are compared, never printed: the other lines in .env are credentials.
ENV_KEYS_WATCHED="AWS_KMS_KEY_ID"
env_value() { sed -n "s/^[[:space:]]*$2[[:space:]]*=[[:space:]]*//p;/^[[:space:]]*$2[[:space:]]*=/q" "$1" 2>/dev/null | tr -d "\"'" | head -1; }

# ---------------------------------------------------------------- merge debt
# "A round that is ACCEPTED and resolved goes to main before the next one starts" — operator rule,
# 2026-09-27. Stated in AGENTS.md, and made visible here so it is checkable rather than remembered.
#
# The definitions are lifted from scripts/merge-accepted.sh gates 1 and 2 ON PURPOSE. If this file
# and the merge gate disagreed about which commit a round audited, the check would be worse than
# none — it would report debt that the gate would not, or clear debt the gate would refuse. Same
# awk, same COMMIT: line, same ancestor test.
round_verdict() {  # $1=log $2=round number
  awk -v n="$2" '
    $0 ~ "^ROUND "n" · AUDITOR " { inb=1; next }
    /^ROUND [0-9]+ · (LEAD|AUDITOR) / { inb=0 }
    inb && /^VERDICT:/ { sub(/^VERDICT:[[:space:]]*/, ""); print $1; exit }' "$1" 2>/dev/null
}
round_commit() {   # $1=log $2=round number
  awk -v n="$2" '
    $0 ~ "^ROUND "n" · LEAD " { inb=1; next }
    /^ROUND [0-9]+ · (LEAD|AUDITOR) / { inb=0 }
    inb && /^COMMIT:/ { sub(/^COMMIT:[[:space:]]*/, ""); print $1; exit }' "$1" 2>/dev/null
}

# ---------------------------------------------------------------- findings (ANCHORED)
# Unanchored (`\bF1.1 MUST`) matches a lead's prose ABOUT a finding — it reported two phantom open
# findings on 2026-09-21. chore/security fixed this in .githooks/commit-msg by anchoring to line
# start; that fix has not reached main, and scripts/audit-findings.sh on main is still unanchored.
open_findings() {
  local f="$1"; [ -f "$f" ] || return 0
  local decl clos
  decl="$(grep -oE '^[[:space:]]{0,6}F[0-9]+\.[0-9]+[[:space:]]+(MUST|SHOULD)\b' "$f" 2>/dev/null | awk '{print $1}' | sort -u)"
  clos="$(grep -oE '^[[:space:]]{0,6}F[0-9]+\.[0-9]+[[:space:]]+(CLOSED|DECLINED)\b' "$f" 2>/dev/null | awk '{print $1}' | sort -u)"
  comm -23 <(echo "$decl") <(echo "$clos") 2>/dev/null | grep -E '^F' || true
}

# ================================================================= write it
{
